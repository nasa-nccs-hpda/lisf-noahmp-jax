"""Extract the DATA tables of CLSM F2.5 (SIBALB albedo tables, PMONTH vegetation tables) from the Fortran source into
clsm_tables.py so that no number is typed by hand.  usage: python3 gen_clsm_tables.py <clsmf25_model.F90> <clsmf25_pmonth_stage4.F90>"""
import re, sys
import numpy as np


def clean(src):
    out = []
    for l in src.split("\n"):
        l = l.split("!")[0]
        out.append(l)
    s = "\n".join(out)
    s = re.sub(r"&\s*\n\s*&?", " ", s)
    return s


def parse_list(txt, consts):
    vals = []
    for tok in txt.split(","):
        tok = tok.strip()
        if not tok:
            continue
        m = re.match(r"^(\d+)\s*\*\s*(.+)$", tok)
        rep, v = (int(m.group(1)), m.group(2).strip()) if m else (1, tok)
        v = consts.get(v.upper(), v)
        v = re.sub(r"[dD]", "e", str(v)) if re.match(r"^[0-9.+-]+[dD]", str(v)) else v
        vals += [float(v)] * rep
    return vals


def sib_tables(path):
    s = clean(open(path).read())
    i = s.index("SUBROUTINE SIBALB")
    s = s[i:]
    consts = {}
    for m in re.finditer(r"REAL,\s*PARAMETER\s*::\s*(\w+)\s*=\s*([0-9.eE+-]+)", s):
        consts[m.group(1).upper()] = m.group(2)
    tabs = {}
    for name in ("ALVDR", "BTVDR", "GMVDR", "ALIDR", "BTIDR", "GMIDR"):
        arr = np.full((14, 2, 9), np.nan)
        for m in re.finditer(r"DATA\s*\(\s*%s\s*\(\s*I\s*,\s*(\d)\s*,\s*(\d)\s*\)\s*,\s*I\s*=\s*1\s*,\s*14\s*\)\s*/([^/]*)/" % name, s):
            j, k = int(m.group(1)), int(m.group(2))
            v = parse_list(m.group(3), consts)
            assert len(v) == 14, (name, j, k, len(v))
            arr[:, j - 1, k - 1] = v
        assert not np.isnan(arr).any(), name
        tabs[name] = arr
    snw = re.search(r"DATA\s+SNWMID\s*/([^/]*)/", s)
    tabs["SNWMID"] = np.array(parse_list(snw.group(1), {}))
    return tabs


def pm_tables(path):
    s = clean(open(path).read())
    tabs = {}
    for name, shape in (("VGZ0", (13, 10)), ("VGDD", (13, 10))):
        m = re.search(r"DATA\s+%s\s*/([^/]*)/" % name, s)
        v = parse_list(m.group(1), {})
        assert len(v) == shape[0] * shape[1], (name, len(v))
        tabs[name] = np.array(v).reshape(shape, order="F")
    for name, n in (("VGRDA", 8), ("VGRDB", 8)):
        m = re.search(r"data\s+%s\s*/([^/]*)/" % name, s, re.I)
        tabs[name] = np.array(parse_list(m.group(1), {}))
    for name in ("VGRF11", "VGRF12", "VGTR11", "VGTR12", "VGROCA", "VGROTD", "VGRDRS", "VGZ2", "VGRT"):
        m = re.search(r"DATA\s+%s\s*/([^/]*)/" % name, s, re.I)
        tabs[name] = np.array(parse_list(m.group(1), {}))
    m = re.search(r"DATA\s+AKDAY0\s*/([^/]*)/", s)
    tabs["AKDAY0"] = np.array(parse_list(m.group(1), {}))
    return tabs


if __name__ == "__main__":
    t = sib_tables(sys.argv[1]); t.update(pm_tables(sys.argv[2]))
    with open(__file__.replace("gen_clsm_tables.py", "clsm_tables.py"), "w") as f:
        f.write('"""Generated by gen_clsm_tables.py from the CLSM F2.5 Fortran source - do not edit."""\nimport numpy as np\n')
        for k, v in t.items():
            f.write(f"{k} = np.array({np.array2string(v, separator=', ', threshold=100000, max_line_width=140, precision=10, floatmode='unique')}, dtype=np.float32)\n")
    print({k: v.shape for k, v in t.items()})
