#!/bin/bash
# Build the standalone Noah 3.9 Fortran baseline with the Rocke3D mentor toolchain (ifort 19.1.3).
# Usage: ./build.sh [suffix] [extra flags...]   e.g. ./build.sh _O0 -O0   (default: -O2, binary noah39_driver)
set -e
cd "$(dirname "$0")"
SUF="${1:-}"; shift || true
source /usr/share/lmod/lmod/init/bash
module load intel/2020Update4
export PATH=$INTEL_BIN:$PATH
P=../../lis/surfacemodels/land/noah.3.9/phys
OPT="${@:--O2}"
FLAGS="$OPT -ftz -assume protect_parens -fp-model strict -fpp"
python3 gen_inc.py
B=build$SUF
mkdir -p $B && cd $B
echo "! intentionally empty: LIS_misc.h is generated by LIS configure" > LIS_misc.h
ifort $FLAGS -I. -c ../$P/module_model_constants_39.F90 ../$P/module_sf_noah39lsm.F90 2>&1 | grep -v remark || true
ifort $FLAGS -I. -I.. -c ../driver.F90 -o driver.o 2>&1 | grep -v remark || true
ifort driver.o module_sf_noah39lsm.o module_model_constants_39.o -o ../noah39_driver$SUF
echo "built noah39_driver$SUF with: $FLAGS"
