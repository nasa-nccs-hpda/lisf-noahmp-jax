"""Write spec_idx.inc (Fortran index constants) from spec.py so the driver and Python agree."""
import spec

lines = ["! generated by gen_inc.py from spec.py; do not edit"]
for prefix, names in (("s", spec.STATIC), ("i", spec.INIT), ("f", spec.FORC), ("o", spec.OUT)):
    for k, n in enumerate(names, 1):
        lines.append(f"integer, parameter :: {prefix}_{n} = {k}")
    lines.append(f"integer, parameter :: n_{prefix} = {len(names)}")
open("spec_idx.inc", "w").write("\n".join(lines) + "\n")
